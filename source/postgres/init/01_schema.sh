#!/bin/bash
# Runs once, on first start of an empty data directory (docker-entrypoint-initdb.d).
# Creates the operational schema `core`, the service roles and the CDC publication.
set -eo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE SCHEMA core;

    CREATE TABLE core.merchants (
        merchant_id        BIGINT PRIMARY KEY,
        name               TEXT        NOT NULL,
        mcc                VARCHAR(4)  NOT NULL,
        province           TEXT        NOT NULL,
        risk_level         TEXT        NOT NULL CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
        owner_national_id  VARCHAR(10) NOT NULL,
        owner_mobile       VARCHAR(11) NOT NULL,
        updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE core.transactions (
        transaction_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        merchant_id     BIGINT      NOT NULL,
        channel         TEXT        NOT NULL CHECK (channel IN ('POS', 'IPG', 'QR')),
        card_bin        VARCHAR(6)  NOT NULL,
        amount          BIGINT      NOT NULL,
        fee_amount      BIGINT      NOT NULL,
        status          TEXT        NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED')),
        created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    -- Full before-images on UPDATE/DELETE so hard deletes still carry created_at/merchant_id
    -- downstream (needed to retract a deleted transaction from the right day/partition).
    ALTER TABLE core.merchants    REPLICA IDENTITY FULL;
    ALTER TABLE core.transactions REPLICA IDENTITY FULL;

    -- Application role used by the change simulator.
    CREATE ROLE ${PG_APP_USER} LOGIN PASSWORD '${PG_APP_PASSWORD}';
    GRANT USAGE ON SCHEMA core TO ${PG_APP_USER};
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA core TO ${PG_APP_USER};
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA core TO ${PG_APP_USER};

    -- CDC role: replication + read only. The publication is created here by the owner,
    -- so Debezium does not need ownership of the tables.
    CREATE ROLE ${PG_CDC_USER} LOGIN REPLICATION PASSWORD '${PG_CDC_PASSWORD}';
    GRANT USAGE ON SCHEMA core TO ${PG_CDC_USER};
    GRANT SELECT ON ALL TABLES IN SCHEMA core TO ${PG_CDC_USER};
    CREATE PUBLICATION dbz_publication FOR TABLE core.merchants, core.transactions;

    -- Read-only BI role: the legacy Metabase connection and the reconciliation test.
    CREATE ROLE ${PG_READER_USER} LOGIN PASSWORD '${PG_READER_PASSWORD}';
    GRANT USAGE ON SCHEMA core TO ${PG_READER_USER};
    GRANT SELECT ON ALL TABLES IN SCHEMA core TO ${PG_READER_USER};
EOSQL

# Replication connections are not matched by "all" in pg_hba.conf.
echo "host replication ${PG_CDC_USER} all scram-sha-256" >> "$PGDATA/pg_hba.conf"
